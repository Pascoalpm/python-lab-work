# arithmetic.py - Программа для решения математических задач
print("=== Решить пример ===")
print("Рассчитать: 4 * 100 - 54")

# Запрос ответа пользователя
user_answer = input("Ваш ответ: ")

# Вычислить правильный ответ
correct_answer = 4 * 100 - 54

# Вывести результаты
print(f"\n--- Результаты ---")
print(f"Ваш ответ: {user_answer}")
print(f"Правильный ответ: {correct_answer}")

# Проверьте, правильно ли вы ответили
try:
	if int(user_answer) == correct_answer:
		print("✅ Поздравляем! Ваш ответ правильный!")
	else:
		print("❌ Неверный ответ. Попробуйте ещё раз!")
except ValueError:
		print("⚠️ Пожалуйста, введите допустимое число!")





